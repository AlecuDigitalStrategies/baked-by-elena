import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, join, sep } from 'node:path';

const root = resolve(process.cwd());
const output = resolve(root, 'dist');
const marker = join(output, '.maison-dulce-generated');
if (output !== join(root, 'dist') || !output.startsWith(`${root}${sep}`)) {
  throw new Error('Directorul de publicare nu este în proiect.');
}
if (existsSync(output)) {
  if (!existsSync(marker)) throw new Error('dist există, dar nu a fost creat de acest build. Nu îl șterg.');
  await rm(output, { recursive: true, force: true });
}
await mkdir(output, { recursive: true });

const pages = ['index.html', 'produs.html', 'script.js', 'product.js', 'product-data.js', 'site-data.js', 'styles.css', 'data.json'];
for (const file of pages) await cp(join(root, file), join(output, file));
await cp(join(root, 'assets'), join(output, 'assets'), { recursive: true });
for (const file of ['index.html', 'admin.css', 'admin.js', 'products-editor.js', 'invite-entry.js']) {
  await mkdir(join(output, 'admin'), { recursive: true });
  await cp(join(root, 'admin', file), join(output, 'admin', file));
}
await writeFile(marker, 'Generated by scripts/build.mjs\n');

const data = JSON.parse(await readFile(join(output, 'data.json'), 'utf8'));
if (!Array.isArray(data.galerie?.imagini)) throw new Error('data.json nu conține galerie.imagini.');
console.log(`Site pregătit pentru Netlify: ${data.galerie.imagini.length} imagini în data.json.`);
